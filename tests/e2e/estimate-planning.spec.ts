test("a homeowner compares battery backup at a common load and starting charge", async ({ page }, testInfo) => {
  const panels = page.getByRole("tab", { name: "Panels", exact: true });
  await panels.click();
  const planner = page.getByRole("region", { name: "How long could one battery last?" });
  await expect(planner).toHaveCount(0);
  await page.getByRole("button", { name: "Add battery", exact: true }).click();
  const watts = planner.getByRole("textbox", { name: "Total running load (W)" });
  const charge = planner.getByRole("combobox", { name: /Charge at start of outage/ });
  await expect(planner).toContainText("Tesla Powerwall 3: 13.5 hr estimated at 1,000 W");
  await watts.fill("1,500");
  await charge.selectOption("50");
  await expect(planner).toContainText("Tesla Powerwall 3: 4.5 hr");
  const generac = page.getByRole("button", { name: /Generac PWRcell M6/ });
  await expect(generac).toContainText("6 hr");
  await generac.click();
  await expect(planner).toContainText("Generac PWRcell M6: 6 hr");
  expect(await planner.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await testInfo.attach("battery-runtime-planner", { body: await planner.screenshot(), contentType: "image/png" });
  await page.getByRole("tab", { name: "Savings", exact: true }).click();
  await panels.click();
  await expect(watts).toHaveValue("1,500");
  await expect(charge).toHaveValue("50");
  await page.getByRole("button", { name: /Enphase IQ Battery 10T/ }).click();
  await expect(planner).toContainText("Enphase IQ Battery 10T: 3.4 hr");
  await expect(planner.getByRole("link")).toHaveAttribute("href", "https://enphase.com/download/iq-battery-10t-data-sheet");
  await watts.fill("3841");
  await expect(planner).toContainText("No runtime is estimated");
  await watts.fill("-1");
  await expect(watts).toHaveAttribute("aria-invalid", "true");
  await expect(planner).toContainText("Enter a valid load");
  await planner.getByRole("button", { name: "Reset runtime inputs" }).click();
  await expect(watts).toHaveValue("1000");
  await expect(charge).toHaveValue("100");
  await expect(planner).toContainText("Enphase IQ Battery 10T: 10.1 hr");
  await page.getByRole("button", { name: "Battery added", exact: true }).click();
  await expect(planner).toHaveCount(0);
});

test("a homeowner without a quote can save only the questions selected for their site visit", async ({ page }) => {
  const roof = page.getByRole("tab", { name: "Roof & shade" });
  await roof.click();
  const tool = page.getByRole("region", { name: "Installer verification checklist" });
  const link = tool.getByRole("link", { name: "Download site visit agenda" });
  const electrical = tool.getByRole("checkbox", { name: "Electrical service capacity and utility approval" });
  const production = tool.getByRole("checkbox", { name: "Sunlight and expected production" });
  await expect(link).toHaveCount(0);
  await electrical.check();
  await production.check();
  await page.getByRole("tab", { name: "Savings", exact: true }).click();
  await roof.click();
  await expect(tool.getByRole("status")).toHaveText("2 of 5 topics selected");
  await electrical.uncheck();
  const downloadPromise = page.waitForEvent("download");
  await link.click();
  const file = await downloadPromise;
  expect(file.suggestedFilename()).toBe("SolarTelligence-site-visit.txt");
  const path = await file.path();
  expect(path).toBeTruthy();
  const content = await readFile(path!, "utf8");
  expect(content).toContain("What first-year production in kWh");
  expect(content).not.toContain("Does my electrical service");
  expect(content).not.toContain(TEST_ADDRESS);
  await page.reload();
  await roof.click();
  await expect(tool.getByRole("status")).toHaveText("0 of 5 topics selected");
  await expect(link).toHaveCount(0);
});

test("a homeowner downloads a private calendar agenda for a prearranged visit", async ({ page }, testInfo) => {
  const requests: string[] = [];
  page.on("request", req => { if (/^https?:/.test(req.url())) requests.push(req.url() + (req.postData() ?? "")); });
  const roof = page.getByRole("tab", { name: "Roof & shade" });
  await roof.click();
  const tool = page.getByRole("region", { name: "Installer verification checklist" });
  const disclosure = tool.getByText("Add this agenda to my calendar", { exact: true });
  const question = tool.getByRole("checkbox", { name: "Roof condition and usable space" });
  const fileLink = tool.getByRole("link", { name: "Download calendar file (.ics)" });
  await expect(disclosure).toHaveCount(0);
  await question.check();
  await disclosure.click();
  await expect(tool.getByText(/does not book a visit or send an invitation/)).toBeVisible();
  const date = tool.getByLabel("Visit date", { exact: true });
  const time = tool.getByLabel("Start time (Phoenix)", { exact: true });
  await expect(date).toHaveValue("");
  await expect(time).toHaveValue("");
  await date.fill("2028-02-29");
  await expect(fileLink).toHaveCount(0);
  await time.fill("23:45");
  await tool.getByLabel("Visit length").selectOption("90");
  await page.getByRole("tab", { name: "Savings", exact: true }).click();
  await roof.click();
  await disclosure.click();
  await expect(date).toHaveValue("2028-02-29");
  await expect(time).toHaveValue("23:45");
  await expect(tool.getByLabel("Visit length")).toHaveValue("90");
  expect(await tool.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await testInfo.attach("calendar-agenda", { body: await tool.screenshot(), contentType: "image/png" });
  const nextFile = page.waitForEvent("download");
  await fileLink.click();
  const file = await nextFile;
  expect(file.suggestedFilename()).toBe("SolarTelligence-site-visit.ics");
  const contents = (await readFile((await file.path())!, "utf8")).replace(/\r\n /g, "");
  expect(contents).toContain("DTSTART:20280301T064500Z\r\nDTEND:20280301T081500Z");
  expect(contents).toContain("Which roof sections");
  expect(contents).not.toMatch(/Does my electrical service|ATTENDEE|ORGANIZER|LOCATION/);
  expect(contents).not.toContain(TEST_ADDRESS);
  await question.uncheck();
  await expect(disclosure).toHaveCount(0);
  await page.reload();
  await roof.click();
  await question.check();
  await disclosure.click();
  await expect(date).toHaveValue("");
  await expect(time).toHaveValue("");
  expect(requests.some(value => /2028-02-29|20280301T064500Z|\/api\/leads(?:\?|$)/.test(value))).toBe(false);
});

test("a homeowner can pin, adjust, replace and clear a roof setup", async ({ page }, testInfo) => {
  const savings = page.getByRole("tab", { name: "Savings", exact: true });
  const tool = page.getByRole("region", { name: "Compare two setups" });
  await savings.click();
  await tool.getByRole("button", { name: "Pin current setup" }).click();
  await expect(tool.getByRole("status")).toHaveText("Current setup matches your baseline.");
  const battery = tool.getByRole("row", { name: /^Battery / });
  const cost = tool.getByRole("row", { name: /^Installed cost before incentives / });
  const original = await cost.getByRole("cell").first().innerText();
  await page.getByRole("tab", { name: "Panels", exact: true }).click();
  await page.getByRole("button", { name: "Add battery", exact: true }).click();
  await savings.click();
  await expect(battery.getByRole("cell").first()).toHaveText("No battery");
  await expect(battery.getByRole("cell").last()).not.toHaveText("No battery");
  await expect(cost.getByRole("cell").first()).toHaveText(original);
  await expect(cost.getByRole("cell").last()).not.toHaveText(original);
  const layout = await tool.evaluate(el => ({ width: el.clientWidth, content: el.scrollWidth }));
  expect(layout.content).toBeLessThanOrEqual(layout.width + 1);
  await testInfo.attach("setup-comparison", { body: await tool.screenshot(), contentType: "image/png" });
  await tool.getByRole("button", { name: "Replace baseline with current" }).click();
  await expect(tool.getByRole("status")).toHaveText("Current setup matches your baseline.");
  await tool.getByRole("button", { name: "Clear baseline" }).click();
  await expect(tool.getByRole("table")).toHaveCount(0);
  await expect(tool.getByRole("status")).toHaveText("No baseline pinned.");
  await expect(tool.getByRole("button", { name: "Pin current setup" })).toBeFocused();
});

test("two installer offers compare total and per-watt prices without sharing quote data", async ({ page }, testInfo) => {
  const requests: string[] = [];
  page.on("request", req => requests.push(req.url() + (req.postData() ?? "")));
  const finance = page.getByRole("tab", { name: "Financing", exact: true });
  await finance.click();
  const buy = page.getByRole("button", { name: "Buy", exact: true });
  await buy.click();
  const tool = page.getByRole("region", { name: "Check an installer's cash quote" });
  const a = tool.getByRole("group", { name: "Quote A", exact: true });
  const b = tool.getByRole("group", { name: "Quote B", exact: true });
  await a.getByLabel("Quoted cash price ($)", { exact: true }).fill("24000");
  await a.getByLabel("Quoted system size (kW DC)", { exact: true }).fill("8");
  await tool.getByRole("button", { name: "Compare a second cash quote" }).click();
  const table = tool.getByRole("table", { name: "Installer cash offers side by side" });
  await b.getByLabel("Quoted cash price ($)", { exact: true }).fill("26091.37");
  const sizeB = b.getByLabel("Quoted system size (kW DC)", { exact: true });
  await sizeB.fill("0");
  await expect(sizeB).toHaveAttribute("aria-invalid", "true");
  await expect(table).toHaveCount(0);
  await sizeB.fill("10");
  await expect(tool.getByText(/costs \$2,091.37 more in total\. Quote B is \$0.39\/W lower/)).toBeVisible();
  await expect(table.getByRole("row", { name: /Price per watt/ })).toHaveText(/\$3\.00\/W\$2\.61\/W/);
  expect(await table.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await testInfo.attach("two-cash-quotes", { body: await table.screenshot(), contentType: "image/png" });
  const nextFile = page.waitForEvent("download");
  await tool.getByRole("link", { name: "Download quote comparison" }).click();
  const file = await nextFile;
  expect(file.suggestedFilename()).toBe("SolarTelligence-cash-offers.txt");
  const contents = await readFile((await file.path())!, "utf8");
  expect(contents).toContain("Quote B $26,091.37");
  expect(contents).not.toContain(TEST_ADDRESS);
  await page.getByRole("tab", { name: "Savings", exact: true }).click();
  await finance.click();
  await expect(sizeB).toHaveValue("10");
  await a.getByLabel("Quoted system size (kW DC)", { exact: true }).fill("");
  await expect(table).toHaveCount(0);
  await expect(tool.getByRole("link", { name: "Download quote comparison" })).toHaveCount(0);
  await tool.getByRole("button", { name: "Remove quote B" }).click();
  await expect(a.getByLabel("Quoted cash price ($)", { exact: true })).toHaveValue("24000");
  await tool.getByRole("button", { name: "Compare a second cash quote" }).click();
  await expect(sizeB).toHaveValue("");
  await b.getByLabel("Quoted cash price ($)", { exact: true }).fill("26091.37");
  await page.reload();
  await finance.click();
  await buy.click();
  await expect(b).toHaveCount(0);
  expect(await page.evaluate(() => JSON.stringify([localStorage, sessionStorage]))).not.toContain("26091.37");
  expect(requests.filter(r => !r.startsWith("data:")).some(r => r.includes("26091.37"))).toBe(false);
});

test("a cash quote validates, survives tab changes, and clears on refresh", async ({ page }, testInfo) => {
  const financing = page.getByRole("tab", { name: "Financing", exact: true });
  const buy = page.getByRole("button", { name: "Buy", exact: true });
  const tool = page.getByRole("region", { name: "Check an installer's cash quote" });
  const price = tool.getByLabel("Quoted cash price ($)", { exact: true });
  const size = tool.getByLabel("Quoted system size (kW DC)", { exact: true });
  await financing.click();
  await buy.click();
  const reference = await tool.getByText("Modeled solar-only price:").innerText();
  await price.fill("$24,000");
  await size.fill("0");
  await expect(size).toHaveAttribute("aria-invalid", "true");
  await expect(tool.getByRole("status")).not.toContainText("Your quote:");
  await expect(tool.getByText("Prepare my installer meeting brief")).toHaveCount(0);
  await size.fill("8");
  await expect(tool.getByRole("status")).toContainText("Your quote: $3.00/W.");
  await tool.getByText("Prepare my installer meeting brief").click();
  const downloadPromise = page.waitForEvent("download");
  await tool.getByRole("link", { name: "Download brief (.txt)" }).click();
  const downloaded = await downloadPromise;
  expect(downloaded.suggestedFilename()).toBe("SolarTelligence-installer-brief.txt");
  const path = await downloaded.path();
  expect(path).toBeTruthy();
  const text = await readFile(path!, "utf8");
  expect(text).toContain("Quoted cash price: $24,000");
  expect(text).toContain("Ask the installer:");
  expect(text).not.toContain(TEST_ADDRESS);
  await page.getByRole("tab", { name: "Panels", exact: true }).click();
  await page.getByRole("button", { name: "Add battery", exact: true }).click();
  await financing.click();
  await expect(price).toHaveValue("$24,000");
  await expect(tool.getByText("Modeled solar-only price:")).toHaveText(reference);
  await testInfo.attach("cash-quote-comparison", { body: await tool.screenshot(), contentType: "image/png" });
  await tool.getByRole("button", { name: "Clear quote" }).click();
  await expect(size).toHaveValue("");
  await expect(price).toHaveValue("");
  await expect(price).toBeFocused();
  await price.fill("18000");
  await page.reload();
  await financing.click();
  await buy.click();
  await expect(price).toHaveValue("");
});
