import { readFile } from "node:fs/promises";
import { expect, test } from "playwright/test";

test("attention shortcut, queue filters and CSV all use the same saved follow-ups", async ({ page }) => {
  await page.goto("/dashboard");
  await page.locator('input[type="password"]').fill("dashboard-workspace-local-qa");
  await page.getByRole("button", { name: "Start secure session" }).click();
  const writes: string[] = [];
  page.on("request", req => { if (req.method() === "POST") writes.push(req.url()); });
  const shortcut = page.getByRole("button", { name: /Follow-ups needing attention/ });
  await expect(shortcut).toBeVisible();
  const attentionCount = Number(await shortcut.locator(".crm-priority-count").innerText());
  expect(attentionCount).toBeGreaterThan(0);
  await shortcut.click();
  const filter = page.getByRole("combobox", { name: /Queue filter/ });
  await expect(filter).toHaveValue("attention");
  const cards = page.locator(".crm-followup-list article");
  await expect(cards).toHaveCount(attentionCount);
  const states = await cards.locator(".crm-status-pill").allTextContents();
  expect(states.every(s => s === "failed" || s === "needs review")).toBe(true);
  await expect(page.getByRole("button", { name: "Send now" })).toHaveCount(0);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export view" }).click();
  const file = await download;
  expect(file.suggestedFilename()).toBe("solartelligence-follow-ups-attention-30-days.csv");
  const lines = (await readFile((await file.path())!, "utf8")).trim().split(/\r?\n/);
  expect(lines.shift()).toBe("follow_up_id,lead_id,channel,status,scheduled_at_utc");
  expect(lines).toHaveLength(attentionCount);
  expect(lines.map(line => line.split(",")[3])).toEqual(states.map(s => s.replaceAll(" ", "_")));
  await filter.selectOption("due");
  await expect(cards).toHaveCount(1);
  await filter.selectOption("upcoming");
  await expect(cards.first()).toBeVisible();
  await filter.selectOption("unscheduled");
  await expect(page.getByText("No matches: Missing schedule")).toBeVisible();
  await page.getByRole("button", { name: "Show all follow-ups" }).click();
  await expect(filter).toHaveValue("all");
  expect(await cards.count()).toBeGreaterThan(attentionCount);
  await filter.selectOption("sent");
  await expect(cards.first().locator(".crm-status-pill")).toHaveText("sent");
  expect(writes.filter(url => url.includes("/api/"))).toEqual([]);
});
