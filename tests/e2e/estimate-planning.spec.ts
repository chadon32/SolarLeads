import { test, expect } from "playwright/test";
import { readFile } from "node:fs/promises";
import { installSafeApiMocks } from "../helpers/network";
import { TEST_ADDRESS } from "../fixtures/test-data";
import { HomeEstimatePage } from "./pages/home-estimate-page";

test.beforeEach(async ({ page }) => {
  await installSafeApiMocks(page);
  await new HomeEstimatePage(page).openReadyEstimate();
});

test("a homeowner can pin, adjust, replace and clear a roof setup", async ({ page }, testInfo) => {
  const savings = page.getByRole("tab", { name: "Savings", exact: true });
  const tool = page.getByRole("region", { name: "Compare two setups" });
  await savings.click();
  await tool.getByRole("button", { name: "Pin current setup" }).click();
  await expect(tool.getByRole("status")).toHaveText("Current setup matches your baseline.");
  const battery = tool.getByRole("row", { name: /^Battery / });
  const cost = tool.getByRole("row", { name: /^Installed cost before incentives / });
  const original = await cost.getByRole("cell").first().innerText();
  await page.getByRole("tab", { name: "Panels", exact: true }).click();
  await page.getByRole("button", { name: "Add battery", exact: true }).click();
  await savings.click();
  await expect(battery.getByRole("cell").first()).toHaveText("No battery");
  await expect(battery.getByRole("cell").last()).not.toHaveText("No battery");
  await expect(cost.getByRole("cell").first()).toHaveText(original);
  await expect(cost.getByRole("cell").last()).not.toHaveText(original);
  const layout = await tool.evaluate(el => ({ width: el.clientWidth, content: el.scrollWidth }));
  expect(layout.content).toBeLessThanOrEqual(layout.width + 1);
  await testInfo.attach("setup-comparison", { body: await tool.screenshot(), contentType: "image/png" });
  await tool.getByRole("button", { name: "Replace baseline with current" }).click();
  await expect(tool.getByRole("status")).toHaveText("Current setup matches your baseline.");
  await tool.getByRole("button", { name: "Clear baseline" }).click();
  await expect(tool.getByRole("table")).toHaveCount(0);
  await expect(tool.getByRole("status")).toHaveText("No baseline pinned.");
  await expect(tool.getByRole("button", { name: "Pin current setup" })).toBeFocused();
});

test("a cash quote validates, survives tab changes, and clears on refresh", async ({ page }, testInfo) => {
  const financing = page.getByRole("tab", { name: "Financing", exact: true });
  const buy = page.getByRole("button", { name: "Buy", exact: true });
  const tool = page.getByRole("region", { name: "Check an installer's cash quote" });
  const price = tool.getByLabel("Quoted cash price ($)", { exact: true });
  const size = tool.getByLabel("Quoted system size (kW DC)", { exact: true });
  await financing.click();
  await buy.click();
  const reference = await tool.getByText("Modeled solar-only price:").innerText();
  await price.fill("$24,000");
  await size.fill("0");
  await expect(size).toHaveAttribute("aria-invalid", "true");
  await expect(tool.getByRole("status")).not.toContainText("Your quote:");
  await expect(tool.getByText("Prepare my installer meeting brief")).toHaveCount(0);
  await size.fill("8");
  await expect(tool.getByRole("status")).toContainText("Your quote: $3.00/W.");
  await tool.getByText("Prepare my installer meeting brief").click();
  const downloadPromise = page.waitForEvent("download");
  await tool.getByRole("link", { name: "Download brief (.txt)" }).click();
  const downloaded = await downloadPromise;
  expect(downloaded.suggestedFilename()).toBe("SolarTelligence-installer-brief.txt");
  const path = await downloaded.path();
  expect(path).toBeTruthy();
  const text = await readFile(path!, "utf8");
  expect(text).toContain("Quoted cash price: $24,000");
  expect(text).toContain("Ask the installer:");
  expect(text).not.toContain(TEST_ADDRESS);
  await page.getByRole("tab", { name: "Panels", exact: true }).click();
  await page.getByRole("button", { name: "Add battery", exact: true }).click();
  await financing.click();
  await expect(price).toHaveValue("$24,000");
  await expect(tool.getByText("Modeled solar-only price:")).toHaveText(reference);
  await testInfo.attach("cash-quote-comparison", { body: await tool.screenshot(), contentType: "image/png" });
  await tool.getByRole("button", { name: "Clear quote" }).click();
  await expect(size).toHaveValue("");
  await expect(price).toHaveValue("");
  await expect(price).toBeFocused();
  await price.fill("18000");
  await page.reload();
  await financing.click();
  await buy.click();
  await expect(price).toHaveValue("");
});
